"""
Application configuration using pydantic-settings.
All settings are read from environment variables or .env file.
"""
from functools import lru_cache
from pathlib import Path
from typing import Any, List, Optional

from pydantic import Field, field_validator, model_validator
from pydantic_settings import BaseSettings, SettingsConfigDict

_BACKEND_DIR = Path(__file__).resolve().parent.parent
_ROOT_DIR = _BACKEND_DIR.parent


class Settings(BaseSettings):
    """Application settings loaded from environment variables."""

    model_config = SettingsConfigDict(
        env_file=(_ROOT_DIR / ".env", _BACKEND_DIR / ".env", ".env"),
        env_file_encoding="utf-8",
        case_sensitive=False,
        extra="ignore",
    )

    # Database
    DATABASE_URL: str = "sqlite:///./testpilot.db"

    # Environment
    ENVIRONMENT: str = "development"

    # Security & JWT
    SECRET_KEY: str = Field("change-me-in-production", repr=False)
    SECRET_ENCRYPTION_KEY: Optional[str] = Field(None, repr=False)
    JWT_ALGORITHM: str = "HS256"
    ACCESS_TOKEN_EXPIRE_MINUTES: int = 480  # 8 hours
    ALLOW_PUBLIC_REGISTRATION: bool = True

    # Password Reset & Email Configuration
    PASSWORD_RESET_TOKEN_EXPIRE_MINUTES: int = 60
    FRONTEND_URL: str = "http://localhost:5173"
    SMTP_HOST: Optional[str] = None
    SMTP_PORT: int = 587
    SMTP_USER: Optional[str] = None
    SMTP_PASSWORD: Optional[str] = Field(None, repr=False)
    SMTP_TLS: bool = True
    EMAILS_FROM_EMAIL: Optional[str] = None
    EMAILS_FROM_NAME: str = "Noetrix"

    @model_validator(mode="after")
    def validate_production_security(self) -> "Settings":
        env = (self.ENVIRONMENT or "").strip().lower()
        secret = (self.SECRET_KEY or "").strip()
        if not secret:
            raise ValueError("SECRET_KEY must not be empty.")

        insecure_keys = {
            "change-me-in-production",
            "change-this-in-production",
            "change-this-to-a-long-random-string-in-production",
            "local-development-only-not-for-production",
            "test-secret-key-12345678901234567890",
            "secret",
            "password",
            "12345678",
            "change-me",
            "test-secret-key-123",
        }

        if env == "production":
            if "SECRET_KEY" not in self.model_fields_set:
                raise ValueError(
                    "SECRET_KEY must be explicitly configured in production."
                )
            if secret.lower() in insecure_keys:
                raise ValueError(
                    "Default or insecure SECRET_KEY is not permitted in production. "
                    "Set a production secret generated by a cryptographically secure random generator."
                )
            if len(secret) < 32:
                raise ValueError(
                    "In production, SECRET_KEY must meet the minimum length of 32 characters."
                )
            if len(set(secret)) < 8:
                raise ValueError(
                    "In production, SECRET_KEY must meet the minimum format check of 8 distinct characters."
                )
        elif len(secret) < 8:
            raise ValueError("SECRET_KEY must be at least 8 characters long.")

        return self

    # CORS
    CORS_ORIGINS: str = "http://localhost:5173,http://127.0.0.1:5173,http://localhost:3000,http://127.0.0.1:3000"

    # Artifacts storage
    ARTIFACTS_DIR: str = "./artifacts"

    # Upload limits
    MAX_UPLOAD_SIZE_MB: int = 10

    # Playwright
    PLAYWRIGHT_HEADLESS: bool = False
    PLAYWRIGHT_TIMEOUT_MS: int = 30000
    PLAYWRIGHT_NAVIGATION_TIMEOUT_MS: int = 30000

    # Live Discovery
    DISCOVERY_SESSION_TIMEOUT_MINUTES: int = 15
    ALLOW_LOCAL_DISCOVERY: bool = False

    @field_validator("ALLOW_LOCAL_DISCOVERY", mode="before")
    @classmethod
    def parse_allow_local_discovery(cls, v: Any) -> bool:
        if isinstance(v, bool):
            return v
        if isinstance(v, (int, float)):
            return bool(v)
        if isinstance(v, str):
            v_clean = v.strip().lower()
            if v_clean in ("true", "1", "yes", "on", "t"):
                return True
            return False
        return bool(v)

    @field_validator("PLAYWRIGHT_HEADLESS", mode="before")
    @classmethod
    def parse_playwright_headless(cls, v: Any) -> bool:
        """Coerce boolean environment variables and strings reliably."""
        if isinstance(v, bool):
            return v
        if isinstance(v, (int, float)):
            return bool(v)
        if isinstance(v, str):
            v_clean = v.strip().lower()
            if v_clean in ("false", "0", "no", "off", "f"):
                return False
            if v_clean in ("true", "1", "yes", "on", "t"):
                return True
        return bool(v)

    @property
    def cors_origins_list(self) -> List[str]:
        """Parse comma-separated CORS origins into a list."""
        return [origin.strip() for origin in self.CORS_ORIGINS.split(",") if origin.strip()]

    @property
    def max_upload_size_bytes(self) -> int:
        """Max upload size in bytes."""
        return self.MAX_UPLOAD_SIZE_MB * 1024 * 1024


@lru_cache()
def get_settings() -> Settings:
    """Return cached application settings."""
    return Settings()
